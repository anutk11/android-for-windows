    public static byte[] glyph(char c) {
        int idx = c - 32;
        if (idx < 0 || idx >= GLYPHS.length) idx = '?' - 32;
        return GLYPHS[idx];
    }

    public static float measureText(String text, float textSize) {
        if (text == null || text.isEmpty()) return 0f;
        float scale = Math.max(1f, textSize / 8f);
        return text.length() * 8f * scale;
    }

    public static void drawText(int[] pixels, int fbW, int fbH,
                                int clipL, int clipT, int clipR, int clipB,
                                String text, float x, float baselineY,
                                float textSize, int argb, boolean bold) {
        if (text == null || text.isEmpty() || pixels == null) return;
        int alpha = (argb >>> 24) & 0xFF;
        if (alpha == 0) return;
        int scale = Math.max(1, Math.round(textSize / 8f));
        int top = Math.round(baselineY) - 7 * scale;
        int startX = Math.round(x);
        int adv = 8 * scale;
        for (int i = 0; i < text.length(); i++) {
            byte[] g = glyph(text.charAt(i));
            int gx = startX + i * adv;
            if (gx + adv < clipL || gx >= clipR) continue;
            for (int row = 0; row < 8; row++) {
                int bits = g[row] & 0xFF;
                if (bold) bits |= (bits >>> 1);
                if (bits == 0) continue;
                int py0 = top + row * scale;
                for (int col = 0; col < 8; col++) {
                    if ((bits & (0x80 >>> col)) == 0) continue;
                    int px0 = gx + col * scale;
                    for (int dy = 0; dy < scale; dy++) {
                        int py = py0 + dy;
                        if (py < clipT || py >= clipB || py < 0 || py >= fbH) continue;
                        int rowOff = py * fbW;
                        for (int dx = 0; dx < scale; dx++) {
                            int px = px0 + dx;
                            if (px < clipL || px >= clipR || px < 0 || px >= fbW) continue;
                            pixels[rowOff + px] = blend(pixels[rowOff + px], argb);
                        }
                    }
                }
            }
        }
    }

    public static int blend(int dst, int src) {
        int sa = (src >>> 24) & 0xFF;
        if (sa == 255) return src;
        if (sa == 0) return dst;
        int ia = 255 - sa;
        int r = ((((src >>> 16) & 0xFF) * sa) + (((dst >>> 16) & 0xFF) * ia)) / 255;
        int g = ((((src >>> 8) & 0xFF) * sa) + (((dst >>> 8) & 0xFF) * ia)) / 255;
        int b = (((src & 0xFF) * sa) + ((dst & 0xFF) * ia)) / 255;
        return 0xFF000000 | (r << 16) | (g << 8) | b;
    }
